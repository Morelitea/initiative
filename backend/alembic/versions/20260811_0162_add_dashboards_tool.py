def downgrade() -> None:
    bind = op.get_bind()
    run_for_each_guild_schema(bind, _apply_downgrade)
    op.execute(_recent_views_trigger_fn(_OLD_RECENT_TABLES))


def _apply_downgrade() -> None:
    # Drop the rows and the permission keys before the tables they reference.
    op.execute(
        "DELETE FROM initiative_role_permissions WHERE permission_key IN "
        "('dashboards_enabled', 'create_dashboards')"
    )
    _swap_permission_key_check(_OLD_PERMISSION_KEYS)
    op.execute("DELETE FROM recent_views WHERE entity_type = 'dashboard'")
    _swap_recent_check(_OLD_RECENT_TYPES)
    op.execute("DELETE FROM resource_grants WHERE resource_type = 'dashboard'")

    with op.batch_alter_table("initiatives", schema=None) as batch_op:
        batch_op.drop_column("dashboards_enabled")

    with op.batch_alter_table("dashboard_tags", schema=None) as batch_op:
        batch_op.drop_index(batch_op.f("ix_dashboard_tags_tag_id"))
    op.drop_table("dashboard_tags")

    with op.batch_alter_table("dashboards", schema=None) as batch_op:
        batch_op.drop_index(batch_op.f("ix_dashboards_listing_uid"))
        batch_op.drop_index(batch_op.f("ix_dashboards_initiative_id"))
        batch_op.drop_index(batch_op.f("ix_dashboards_guild_id"))
