"""add dashboards tool

Adds the ``dashboards`` content table (+ its tag junction) and the
``initiatives.dashboards_enabled`` master switch to every guild schema.

Beyond the autogenerated DDL this carries the manual arms a new tool always
needs, because each is guarded by a CHECK or a CASE that would otherwise reject
the new value at runtime:

* ``ck_initiative_role_permissions_permission_key`` — the stored permission-key
  allow-list gains ``dashboards_enabled`` / ``create_dashboards``.
* ``ck_recent_views_entity_type`` — gains ``'dashboard'``.
* ``public.fn_recent_views_set_guild_id`` — gains a ``dashboard`` CASE arm; a
  recentable type with no arm makes every recent-view INSERT fail with
  CaseNotFoundError.

The allow-lists above are written out literally for the same reason RLS is not
applied here: a migration is a historical record, and anything it reads from the
live app describes a LATER state of the world than the revision it runs at.
Deriving the permission keys from ``PermissionKey`` made this migration reject
rows that a later revision had not deleted yet, so every upgrade from an older
database failed while a fresh one passed.

RLS is deliberately NOT applied here, on the same principle: rendering the live
``INITIATIVE_PATHS`` registry mid-history tries to create policies for tables a
subsequent migration has not created yet. Policies (like table grants, which
already work this way) come from provisioning: the registry change bumps the
provisioning stamp, so the boot back-fill applies them to every guild schema.
Until then the new tables carry no grants either, so no role can reach them.
"""

