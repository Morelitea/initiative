"""calendar container tool

The events tool becomes a Calendar container tool (``Tool.calendar``): a new
``calendars`` table is the shareable DAC anchor and events hang off it via
``calendar_id`` — the same shape as projects → tasks.

Guild-content migration, per schema (``guild_template`` + every ``guild_<id>``):

- create ``calendars`` + ``calendar_tags``;
- backfill one renamable "Default Calendar" per initiative that has events
  (creator = the initiative's earliest event author) and point its events at it;
- seed the default calendar's grants — every ``is_manager`` initiative role at
  ``owner`` plus an all-initiative-members ``read`` row — and drop the old
  per-event ``calendar_event`` grants (sharing is per calendar now);
- swap ``calendar_events.initiative_id`` for NOT NULL ``calendar_id``;
- rename the initiative master switch ``calendar_events_enabled`` →
  ``calendars_enabled`` and the stored permission keys to the new
  ``PermissionKey`` spellings;
- recents: ``calendar`` replaces ``calendar_event`` (events, like tasks, are no
  longer recentable) in the CHECK constraint, the shared trigger function, and
  the stored rows.

RLS policies are re-applied per schema as the final upgrade step by running the
registry-rendered DDL (``render_guild_rls_ddl``) — the same idempotent script
provisioning/boot backfill re-asserts — because ``guild_template`` is not a
provisioning target (the boot backfill enumerates real guilds only) and the
event-table policies must be dropped mid-migration to release the swapped
column. The downgrade does NOT re-render (the running registry describes the
new shape); restored tables stay fail-closed until the deployed code's boot
backfill re-applies its policies. DML here runs as the table owner with
``NO FORCE ROW LEVEL SECURITY`` toggled around it (FORCE would leave the owner
policy-bound and silently skip rows), and the event backfill asserts a zero
orphan count per schema.

Pre-v1 breaking rename — no compatibility shims. Downgrade restores the old
structure; per-event grants are reconstituted as creator-owner +
all-initiative-members read (the pre-migration per-event sharing detail is not
recoverable).
"""

