def _recent_views_trigger_fn(entity_tables) -> str:
    """``public.fn_recent_views_set_guild_id`` with one CASE arm per recentable
    entity type — a type with no arm makes every view of it fail."""
    arms = "\n".join(
        f"""                    WHEN '{etype}' THEN
                        SELECT guild_id INTO NEW.guild_id FROM {table}
                        WHERE id = NEW.entity_id;"""
        for etype, table in entity_tables
    )
    return f"""
        CREATE OR REPLACE FUNCTION public.fn_recent_views_set_guild_id() RETURNS trigger
        LANGUAGE plpgsql
        AS $$
        BEGIN
            IF NEW.guild_id IS NULL OR (TG_OP = 'UPDATE' AND (
                OLD.entity_type IS DISTINCT FROM NEW.entity_type
                OR OLD.entity_id IS DISTINCT FROM NEW.entity_id
            )) THEN
                CASE NEW.entity_type
{arms}
                    ELSE
                        RAISE EXCEPTION
                            'fn_recent_views_set_guild_id has no arm for entity_type %',
                            NEW.entity_type;
                END CASE;
            END IF;
            RETURN NEW;
        END;
        $$
    """


def _swap_recent_check(types) -> None:
    op.execute(
        "ALTER TABLE recent_views DROP CONSTRAINT IF EXISTS ck_recent_views_entity_type"
    )
    op.execute(
        "ALTER TABLE recent_views ADD CONSTRAINT ck_recent_views_entity_type "
        f"CHECK (entity_type = ANY (ARRAY[{_quoted(types)}]))"
    )


def _kind_code_fn(kinds):
    arms = " ".join(f"WHEN '{kind}' THEN {code}" for kind, code, _ in kinds)
    return f"""
        CREATE OR REPLACE FUNCTION public.relationship_kind_code(kind text)
        RETURNS bigint LANGUAGE sql IMMUTABLE STRICT AS $$
            SELECT (CASE kind {arms} END)::bigint
        $$
    """


def _set_guild_id_fn(kinds):
    arms = "\n".join(
        f"""                    WHEN '{kind}' THEN
                        SELECT guild_id INTO NEW.guild_id FROM {table}
                        WHERE id = NEW.source_id;"""
        for kind, _, table in kinds
    )
    return f"""
        CREATE OR REPLACE FUNCTION public.fn_relationships_set_guild_id()
        RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN
            IF NEW.guild_id IS NULL THEN
                CASE NEW.source_type
{arms}
                    ELSE
                        RAISE EXCEPTION
                            'fn_relationships_set_guild_id has no arm for source_type %',
                            NEW.source_type;
                END CASE;
            END IF;
            RETURN NEW;
        END;
        $$
    """


def _retype_endpoint_checks(kinds) -> None:
    """Re-state the two endpoint-kind CHECK constraints over ``kinds``."""
    values = ", ".join(f"'{kind}'" for kind, _, _ in sorted(kinds))
    for side in ("source", "target"):
        name = f"ck_relationships_{side}_type"
        op.execute(f"ALTER TABLE relationships DROP CONSTRAINT IF EXISTS {name}")
        op.execute(
            f"ALTER TABLE relationships ADD CONSTRAINT {name} "
            f"CHECK ({side}_type IN ({values}))"
        )


