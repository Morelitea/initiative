"""add tasks.completed_at

A task is complete exactly when its status sits in the ``done`` category;
``completed_at`` records when it got there, so consumers stop proxying
completion with ``updated_at``.

Existing done tasks are backfilled from ``updated_at`` — the same proxy the
stats service already used for completion time, so no reader gets a worse
answer than it had, and the "done implies a completion timestamp" invariant
holds from the first boot after the upgrade.

The backfill runs as the table owner with FORCE RLS toggled off around it
(FORCE would leave the owner policy-bound and silently skip every row, since a
migration carries no request context) and asserts no done task is left without
a timestamp per schema.
"""

