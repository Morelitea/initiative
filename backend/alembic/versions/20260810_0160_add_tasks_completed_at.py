_BACKFILL = """
UPDATE tasks
   SET completed_at = tasks.updated_at
  FROM task_statuses
 WHERE tasks.task_status_id = task_statuses.id
   AND task_statuses.category = 'done'
   AND tasks.completed_at IS NULL
"""

_REMAINING = """
SELECT count(*)
  FROM tasks
  JOIN task_statuses ON task_statuses.id = tasks.task_status_id
 WHERE task_statuses.category = 'done'
   AND tasks.completed_at IS NULL
"""


